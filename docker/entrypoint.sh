#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# Elveth Group - WordPress container entrypoint
#
# 1. Renders wp-config.php from environment variables (secrets never live in
#    the image or in git).
# 2. Seeds the uploads volume on first boot if a seed copy is present.
# 3. Hands over to the official WordPress entrypoint (apache2-foreground).
# ---------------------------------------------------------------------------
set -euo pipefail

WP_PATH="${WP_PATH:-/var/www/html}"

render_wp_config() {
    cat > "${WP_PATH}/wp-config.php" <<PHPEOF
<?php
/** Generated by docker/entrypoint.sh - do not edit, do not commit. */

define( 'DB_NAME', '${WORDPRESS_DB_NAME}' );
define( 'DB_USER', '${WORDPRESS_DB_USER}' );
define( 'DB_PASSWORD', '${WORDPRESS_DB_PASSWORD}' );
define( 'DB_HOST', '${WORDPRESS_DB_HOST}' );
define( 'DB_CHARSET', 'utf8mb4' );
define( 'DB_COLLATE', '' );

define( 'AUTH_KEY',         '${AUTH_KEY}' );
define( 'SECURE_AUTH_KEY',  '${SECURE_AUTH_KEY}' );
define( 'LOGGED_IN_KEY',    '${LOGGED_IN_KEY}' );
define( 'NONCE_KEY',        '${NONCE_KEY}' );
define( 'AUTH_SALT',        '${AUTH_SALT}' );
define( 'SECURE_AUTH_SALT', '${SECURE_AUTH_SALT}' );
define( 'LOGGED_IN_SALT',   '${LOGGED_IN_SALT}' );
define( 'NONCE_SALT',       '${NONCE_SALT}' );

\$table_prefix = '${WORDPRESS_TABLE_PREFIX}';

define( 'WP_DEBUG', ${WORDPRESS_DEBUG:-false} );
define( 'WP_DEBUG_LOG', ${WORDPRESS_DEBUG_LOG:-false} );
define( 'WP_DEBUG_DISPLAY', ${WORDPRESS_DEBUG_DISPLAY:-false} );

define( 'FS_METHOD', 'direct' );
define( 'DISALLOW_FILE_EDIT', true );
define( 'AUTOMATIC_UPDATER_DISABLED', true );
define( 'WP_AUTO_UPDATE_CORE', 'minor' );
define( 'WP_MEMORY_LIMIT', '512M' );
define( 'WP_MAX_MEMORY_LIMIT', '512M' );

if ( ! defined( 'ABSPATH' ) ) {
	define( 'ABSPATH', __DIR__ . '/' );
}

require_once ABSPATH . 'wp-settings.php';
PHPEOF
    chown www-data:www-data "${WP_PATH}/wp-config.php"
    chmod 640 "${WP_PATH}/wp-config.php"
}

echo "[elveth] rendering wp-config.php"
render_wp_config

# Seed uploads (first boot only) when a seed copy is shipped in the image.
if [ -d /seed/uploads ] && [ -n "$(ls -A /seed/uploads 2>/dev/null || true)" ]; then
    if [ -z "$(ls -A "${WP_PATH}/wp-content/uploads" 2>/dev/null || true)" ]; then
        echo "[elveth] seeding wp-content/uploads"
        cp -a /seed/uploads/. "${WP_PATH}/wp-content/uploads/"
        chown -R www-data:www-data "${WP_PATH}/wp-content/uploads"
    fi
fi

echo "[elveth] starting wordpress"
exec docker-entrypoint.sh "$@"
